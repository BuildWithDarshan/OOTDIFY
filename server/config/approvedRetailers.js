  export function getApprovedRetailers({ enabledOnly = true } = {}) {
      return approvedRetailers.filter(
          (source) => !enabledOnly || source.enabled
      );
  }
  export function getApprovedRetailerById(id) {
      return approvedRetailers.find((source) => source.id === id) ?? null;
  }
  export function getApprovedDomains({ enabledOnly = true } = {}) {
      return getApprovedRetailers({ enabledOnly }).flatMap(
          (source) => source.domains
      );
  }
  export default approvedRetailers;
